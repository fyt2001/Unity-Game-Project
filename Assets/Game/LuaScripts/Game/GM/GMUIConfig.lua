--[[
=============================================================================
GMUIConfig.lua - GM 面板的可调常量（门控通道 / 连点解锁参数）
=============================================================================
说明：
  - 本文件是 GM 模块里「数值/开关类常量」的唯一落点，改动在这里改一处即可，
    不要把 5 / 1.5 这类魔数散到 GMUnlock.lua 或 UILoginView.lua 里。
	  - 正式包关闭解锁通道，构建门控同时阻止遗留设置重新启用。
	        dev "①" = 版本号连点 5 次解锁
        "②" / "③" = 预留通道，未启用时 GMUnlock.Init() 直接 return，连点静默失效，
                     不再产生「写了 GM_Enabled」这种副作用。
=============================================================================
]]

local GMUIConfig = {}

-- 版本号连点解锁：窗口内累计 taps 次即解锁（第 1 次点击不计窗口，直接算第 1 下）
GMUIConfig.TapUnlock = {
	taps      = 5,     -- 需要连点次数
	windowSec = 1.5    -- 相邻两次点击的最大间隔（秒），超时视为新序列、计数重置为 1
}

-- Release remains disabled regardless of the stored preference.
GMUIConfig.Channel = {
	dev     = "①",
	release = "disabled"
}

-- =============================================================================
-- 容量上限（S8 性能降级链的唯一取值口；规格 04_tech_design.md §8.1 / §8.2）
--
-- 口径：这表是【上限】，不是【当前渲染条数】。预算表（§8.1）里「最坏存活 item」
--       由虚拟列表自己算（命令 12 / 分类 14 / 日志 12），本表的 500 / 200 是
--       【列表最多装多少条】【环形缓冲最多留多少条】，两者不是一个数，别混。
--
-- 【硬约束：这两条由 R12 定，不可放宽】
--   logEntryCharLimit  单条日志字符硬上限。超出即截断 + "…"，不做任何"智能摘要"、
--                      不做多轮折叠、不做"只对 error 放宽"的特例 —— 放宽就等于
--                      日志区可能出现 >1024 字符的一条，把 TMP 解析和复制路径一起拖肥。
--   logPersistMode     持久化布局。"perKey" = 逐条分 PlayerPrefs key（GM_Log_00…），
--                      禁止为了省事存成一个大 JSON：单 key ≤3 KB，PlayerPrefs 的
--                      单 key 体积与整体写盘成本都随 key 数线性增长，一个大 JSON
--                      要么撑爆、要么让「最旧的一条」的删除变成整块重写。
-- 其余字段是数值调优空间（改大 = 更全但更贵），改之前先按 §8.2 降级链过一遍。
-- =============================================================================
GMUIConfig.Capacity = {
	logDisplayMax     = 200,       -- 环形缓冲最多留条数（= 面板日志区最多显示条数，超了丢最旧的）
	logPersistMax     = 30,        -- 持久化最近 N 条（逐条分 key：GM_Log_00 … GM_Log_29）
	logEntryCharLimit = 1024,      -- 单条日志字符硬上限（R12，不可放宽）；超出截断 + "…"
	logPersistMode    = "perKey",  -- 持久化布局（R12，不可放宽）：perKey = 逐条分 key
	recentUsedMax     = 20,        -- 最近使用命令上限（当前无消费方，预留）
	favoriteMax       = 50,        -- 收藏上限（当前无消费方，预留）
	cmdListMaxItems   = 500,       -- 命令列表最大项数：虚拟滚动下 500 与 12 同开销，再大没有收益
}

return GMUIConfig
